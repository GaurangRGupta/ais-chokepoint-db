-- Core schema for the Singapore Strait vessel traffic database.
-- Run in pgAdmin Query Tool while connected to database chokepoint.
-- PostGIS and btree_gist must already exist (they do).

CREATE SCHEMA IF NOT EXISTS ais;
CREATE SCHEMA IF NOT EXISTS ops;

COMMENT ON SCHEMA ais IS 'AIS facts: current and history positions, static identity, quarantine.';
COMMENT ON SCHEMA ops IS 'Operator objects: geofences, transits, dwells, ingest heartbeat.';

-- Valid time = when the fact was true in the world (AIS event time, UTC).
-- Ingest time = when this database learned the fact.

CREATE TABLE IF NOT EXISTS ais.vessel_static_current (
    mmsi            integer PRIMARY KEY,
    name            text,
    ship_type       integer,
    callsign        text,
    imo             integer,
    dim_bow_m       integer,
    dim_stern_m     integer,
    dim_port_m      integer,
    dim_starboard_m integer,
    destination     text,
    eta             text,
    valid_time      timestamptz NOT NULL,
    ingest_time     timestamptz NOT NULL DEFAULT clock_timestamp(),
    source          text NOT NULL
);

CREATE TABLE IF NOT EXISTS ais.vessel_static_history (
    mmsi            integer NOT NULL,
    name            text,
    ship_type       integer,
    callsign        text,
    imo             integer,
    dim_bow_m       integer,
    dim_stern_m     integer,
    dim_port_m      integer,
    dim_starboard_m integer,
    destination     text,
    eta             text,
    valid_range     tstzrange NOT NULL,
    ingest_time     timestamptz NOT NULL DEFAULT clock_timestamp(),
    source          text NOT NULL,
    EXCLUDE USING gist (mmsi WITH =, valid_range WITH &&)
);

CREATE TABLE IF NOT EXISTS ais.vessel_position (
    pos_id          bigint GENERATED BY DEFAULT AS IDENTITY,
    mmsi            integer NOT NULL,
    geom            geography(Point, 4326) NOT NULL,
    sog_kn          double precision,
    cog_deg         double precision,
    heading_deg     integer,
    nav_status      integer,
    msg_type        text NOT NULL,
    valid_time      timestamptz NOT NULL,
    ingest_time     timestamptz NOT NULL DEFAULT clock_timestamp(),
    source          text NOT NULL,
    payload_sha256  text NOT NULL,
    PRIMARY KEY (pos_id, valid_time),
    UNIQUE (mmsi, valid_time, payload_sha256)
) PARTITION BY RANGE (valid_time);

CREATE TABLE IF NOT EXISTS ais.vessel_position_current (
    mmsi            integer PRIMARY KEY,
    geom            geography(Point, 4326) NOT NULL,
    sog_kn          double precision,
    cog_deg         double precision,
    heading_deg     integer,
    nav_status      integer,
    msg_type        text NOT NULL,
    valid_time      timestamptz NOT NULL,
    ingest_time     timestamptz NOT NULL,
    source          text NOT NULL
);

CREATE TABLE IF NOT EXISTS ais.quarantine (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    received_at     timestamptz NOT NULL DEFAULT clock_timestamp(),
    reason          text NOT NULL,
    source          text NOT NULL,
    raw             jsonb NOT NULL
);

CREATE TABLE IF NOT EXISTS ops.geofence (
    geofence_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL UNIQUE,
    kind            text NOT NULL CHECK (kind IN ('lane_east', 'lane_west', 'anchorage', 'port_limit')),
    geom            geography(Polygon, 4326) NOT NULL,
    drawn_by        text,
    notes           text
);

CREATE TABLE IF NOT EXISTS ops.transit_event (
    transit_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mmsi            integer NOT NULL,
    geofence_id     integer NOT NULL REFERENCES ops.geofence (geofence_id),
    direction       text NOT NULL CHECK (direction IN ('east', 'west')),
    enter_time      timestamptz NOT NULL,
    leave_time      timestamptz,
    enter_geom      geography(Point, 4326),
    leave_geom      geography(Point, 4326),
    enter_ingest    timestamptz,
    leave_ingest    timestamptz
);

CREATE TABLE IF NOT EXISTS ops.dwell_event (
    dwell_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mmsi            integer NOT NULL,
    geofence_id     integer NOT NULL REFERENCES ops.geofence (geofence_id),
    start_time      timestamptz NOT NULL,
    end_time        timestamptz,
    min_sog         double precision,
    median_sog      double precision
);

CREATE TABLE IF NOT EXISTS ops.ingest_heartbeat (
    ts                          timestamptz PRIMARY KEY DEFAULT clock_timestamp(),
    source                      text NOT NULL,
    connected                   boolean NOT NULL,
    msg_last_minute             integer,
    distinct_mmsi_last_minute   integer,
    lag_p50_s                   double precision,
    lag_p95_s                   double precision
);

CREATE INDEX IF NOT EXISTS vessel_position_current_geom_gix
    ON ais.vessel_position_current USING gist (geom);
CREATE INDEX IF NOT EXISTS vessel_position_current_valid_time_idx
    ON ais.vessel_position_current (valid_time);
CREATE INDEX IF NOT EXISTS geofence_geom_gix
    ON ops.geofence USING gist (geom);
CREATE INDEX IF NOT EXISTS quarantine_reason_idx
    ON ais.quarantine (reason, received_at DESC);
CREATE INDEX IF NOT EXISTS transit_enter_idx
    ON ops.transit_event (enter_time DESC);
CREATE INDEX IF NOT EXISTS dwell_open_idx
    ON ops.dwell_event (geofence_id) WHERE end_time IS NULL;

CREATE OR REPLACE FUNCTION ais.ensure_position_partitions(from_day date, to_day date)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    d date;
    start_ts timestamptz;
    end_ts timestamptz;
    part_name text;
BEGIN
    d := from_day;
    WHILE d < to_day LOOP
        start_ts := d::timestamp AT TIME ZONE 'UTC';
        end_ts := (d + 1)::timestamp AT TIME ZONE 'UTC';
        part_name := format('vessel_position_%s', to_char(d, 'YYYYMMDD'));
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS ais.%I PARTITION OF ais.vessel_position
             FOR VALUES FROM (%L) TO (%L)',
            part_name, start_ts, end_ts
        );
        EXECUTE format(
            'CREATE INDEX IF NOT EXISTS %I ON ais.%I USING gist (geom)',
            part_name || '_geom_gix', part_name
        );
        EXECUTE format(
            'CREATE INDEX IF NOT EXISTS %I ON ais.%I (mmsi, valid_time DESC)',
            part_name || '_mmsi_time_idx', part_name
        );
        d := d + 1;
    END LOOP;
END;
$$;

-- Hot window: yesterday through 7 days ahead, UTC calendar days.
SELECT ais.ensure_position_partitions(
    (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::date - 1,
    (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::date + 8
);

COMMENT ON TABLE ais.vessel_position IS
    'Append-only AIS positions. Partitioned by valid_time (world time), not ingest_time.';
COMMENT ON COLUMN ais.vessel_position.valid_time IS
    'When the position was true in the world (AIS event time, UTC).';
COMMENT ON COLUMN ais.vessel_position.ingest_time IS
    'When this database learned the fact.';
COMMENT ON TABLE ais.vessel_position_current IS
    'Newest valid position per MMSI. Updated only if the incoming valid_time is greater or equal.';
